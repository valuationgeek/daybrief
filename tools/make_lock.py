"""Write the hashed lock files the GitHub workflows install from.

    python tools/make_lock.py
    python tools/make_lock.py --accept GHSA-xxxx-xxxx-xxxx="why it doesn't apply here"

  requirements-ci.lock  ← requirements-ci.txt  (the test job: Linux and Windows, Python 3.11)
  requirements.lock     ← requirements.txt     (digest.yml: Linux, Python 3.11)

Nothing is installed. Each target platform is resolved with
`pip install --dry-run --report`, wheels only. Every pinned version gets the
sha256 of every wheel PyPI publishes for it, so pip can check whichever file
it picks, and is checked against OSV (osv.dev) first. If OSV lists an
advisory, or can't be reached, no lock is written. Only the repository owner
accepts an advisory, with --accept.

Local setup doesn't use these locks: people install daybrief on many
platforms and Python versions, and a hashed lock fits only one of each.
Needs pip 23.1 or later (for --dry-run --report).
"""

import argparse
import json
import subprocess
import sys
import tempfile
import time
import urllib.request
from datetime import date
from pathlib import Path

# pip's own copy, so this script needs nothing pip doesn't already bring.
from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
PYTHON = "3.11"
USER_AGENT = "daybrief-make-lock"

# An explicit --platform matches only the tags listed, so Linux lists every
# glibc level up to the runner's (ubuntu-latest is 24.04, glibc 2.39).
LINUX_TAGS = [f"manylinux_2_{minor}_x86_64" for minor in range(39, 4, -1)]
LINUX_TAGS += ["manylinux2014_x86_64", "manylinux2010_x86_64", "manylinux1_x86_64"]

# What dependency markers ("; platform_system == 'Linux'") are evaluated
# against. pip evaluates them for the machine it runs on even with
# --platform, so resolve() re-walks the graph with these instead.
_COMMON_ENV = {"implementation_name": "cpython", "platform_python_implementation": "CPython",
               "python_version": PYTHON, "python_full_version": PYTHON + ".9",
               "implementation_version": PYTHON + ".9", "platform_release": "", "platform_version": ""}
PLATFORMS = {
    "linux": (LINUX_TAGS, {**_COMMON_ENV, "os_name": "posix", "sys_platform": "linux",
                           "platform_system": "Linux", "platform_machine": "x86_64"}),
    "win32": (["win_amd64"], {**_COMMON_ENV, "os_name": "nt", "sys_platform": "win32",
                              "platform_system": "Windows", "platform_machine": "AMD64"}),
}

# lock file: (source requirements, platforms it must install on)
TARGETS = {
    "requirements-ci.lock": ("requirements-ci.txt", ["linux", "win32"]),
    "requirements.lock": ("requirements.txt", ["linux"]),
}

HEADER = """\
# Exact versions and sha256 hashes, generated by tools/make_lock.py from {source}
# for Python {python} on {platforms}. Every version was checked against OSV
# (osv.dev) on {today}.{accepted}
# Install with: pip install --require-hashes --only-binary :all: -r {lock}
# To refresh: edit {source} if needed, then run python tools/make_lock.py
"""


def fetch_json(url, body=None):
    """GET (or POST body) JSON, retrying a flaky connection a few times."""
    data = json.dumps(body).encode() if body is not None else None
    headers = {"User-Agent": USER_AGENT, "Content-Type": "application/json"}
    error = None
    for attempt in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, data=data, headers=headers), timeout=60) as r:
                return json.load(r)
        except Exception as e:
            error = e
            time.sleep(2 * (attempt + 1))
    raise SystemExit(f"Could not reach {url}: {error}")


def _pip_report(lines, tags):
    """{canonical name: metadata} for what pip resolves from `lines`, wheels only, for `tags`."""
    with tempfile.TemporaryDirectory() as tmp:
        reqs, report = Path(tmp) / "requirements.txt", Path(tmp) / "report.json"
        reqs.write_text("\n".join(lines) + "\n", encoding="utf-8")
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
               "--report", str(report), "--only-binary", ":all:", "--python-version", PYTHON,
               "--implementation", "cp", "--abi", "cp" + PYTHON.replace(".", "")]
        for tag in tags:
            cmd += ["--platform", tag]
        subprocess.run(cmd + ["-r", str(reqs)], check=True)
        installs = json.loads(report.read_text(encoding="utf-8"))["install"]
    return {canonicalize_name(i["metadata"]["name"]): i["metadata"] for i in installs}


def _applies(req, env, extras=("",)):
    return req.marker is None or any(req.marker.evaluate({**env, "extra": e}) for e in extras)


def resolve(source, platform):
    """{name: version} that `source` needs on `platform`.

    pip resolves for the target's wheel tags but evaluates markers for this
    machine, so on Windows a Linux resolve drops torch's CUDA packages and
    keeps pytest's colorama. The graph is walked again with the target's
    markers: anything only this machine needs is left out, and anything the
    target needs that pip skipped is added and resolved again.
    """
    tags, env = PLATFORMS[platform]
    top = [line.split("#", 1)[0].strip() for line in (ROOT / source).read_text(encoding="utf-8").splitlines()]
    top = [Requirement(line) for line in top if line]
    added = []
    for _ in range(10):
        graph = _pip_report([str(r) for r in top] + added, tags)
        wanted, missing, seen = set(), [], set()
        stack = [r for r in top if _applies(r, env)]
        while stack:
            req = stack.pop()
            name, extras = canonicalize_name(req.name), frozenset(req.extras)
            if (name, extras) in seen:
                continue
            seen.add((name, extras))
            if name not in graph:
                missing.append(req)
                continue
            wanted.add(name)
            for dep in graph[name].get("requires_dist") or []:
                dep = Requirement(dep)
                if _applies(dep, env, ("",) + tuple(extras)):
                    stack.append(dep)
        if not missing:
            return {name: graph[name]["version"] for name in wanted}
        for req in missing:
            req.marker = None
            added.append(str(req))
    raise SystemExit(f"{source}: the {platform} dependency graph didn't settle")


def wheel_hashes(name, version):
    files = fetch_json(f"https://pypi.org/pypi/{name}/{version}/json")["urls"]
    hashes = sorted({f["digests"]["sha256"] for f in files if f["packagetype"] == "bdist_wheel"})
    if not hashes:
        raise SystemExit(f"{name}=={version} has no wheel on PyPI; nothing may be built from source")
    return hashes


def advisories(pins):
    """{(name, version): [advisory id, ...]} from OSV, for every pin with one."""
    pins = sorted(pins)
    queries = [{"package": {"name": n, "ecosystem": "PyPI"}, "version": v} for n, v in pins]
    found = {}
    for start in range(0, len(queries), 500):
        results = fetch_json("https://api.osv.dev/v1/querybatch", {"queries": queries[start:start + 500]})["results"]
        for (n, v), result in zip(pins[start:start + 500], results):
            ids = [vuln["id"] for vuln in result.get("vulns") or []]
            if ids:
                found[(n, v)] = ids
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--accept", action="append", default=[], metavar='ID="reason"',
                        help="accept one OSV advisory, with the reason it doesn't apply")
    args = parser.parse_args()
    accepted = dict(a.split("=", 1) for a in args.accept)

    planned = {}
    for lock, (source, platforms) in TARGETS.items():
        by_platform = {plat: resolve(source, plat) for plat in platforms}
        names = sorted(set().union(*by_platform.values()))
        entries = []   # (name, version, marker or None)
        for name in names:
            versions = {plat: pins.get(name) for plat, pins in by_platform.items()}
            if len(set(versions.values())) == 1:
                entries.append((name, versions[next(iter(versions))], None))
            else:
                entries += [(name, v, plat) for plat, v in versions.items() if v]
        planned[lock] = (source, platforms, entries)
        print(f"{lock}: {len(entries)} pins")

    all_pins = {(n, v) for _, _, entries in planned.values() for n, v, _ in entries}
    found = advisories(all_pins)
    unaccepted = {pin: [i for i in ids if i not in accepted] for pin, ids in found.items()}
    unaccepted = {pin: ids for pin, ids in unaccepted.items() if ids}
    if unaccepted:
        for (n, v), ids in sorted(unaccepted.items()):
            print(f"  {n}=={v}: {', '.join(ids)}")
        raise SystemExit("OSV lists advisories for the pins above. No lock was written. Upgrade them, "
                         "or have the repository owner accept each with --accept ID=\"reason\".")

    for lock, (source, platforms, entries) in planned.items():
        accepted_here = [f"{i}: {accepted[i]}" for (n, v), ids in found.items()
                         if any(n == e[0] and v == e[1] for e in entries) for i in ids]
        lines = [HEADER.format(
            source=source, python=PYTHON, platforms=" and ".join(sorted(platforms)), today=date.today(), lock=lock,
            accepted="".join(f"\n# Accepted advisory {a}" for a in accepted_here),
        )]
        for name, version, marker in entries:
            spec = f"{name}=={version}" + (f' ; sys_platform == "{marker}"' if marker else "")
            hashes = wheel_hashes(name, version)
            lines.append(spec + " \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes) + "\n")
        (ROOT / lock).write_text("".join(lines), encoding="utf-8", newline="\n")
        print(f"Wrote {lock}")


if __name__ == "__main__":
    main()
